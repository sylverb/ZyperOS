#!/usr/bin/env python3
"""On-Screen Stats' glyphs (src/hud.h): the few characters its line writes,
the digits, "." and ":", the units ("fps", "x", "°C", "CPU", "%", "GHz",
"MHz", "AM", "PM") and the middle dot between items, in Lexend Regular
(res/fonts/menu.ttf) at the line's two sizes, the design's support type
(DS_TYPE_SUPPORT, Normal) and chrome type (DS_TYPE_CHROME, Small), as alpha
bitmaps in a C header, src/hudglyphs.h, at the two scales the line is drawn
at: 1 (the launcher's 1024-unit screen, its page's preview and its shots)
and 0.625 (Diatom on the Pixel 2's 640x480 panel). Diatom has no font
engine, and needs none for a few dozen characters; drawn here once, by the
same font the launcher draws with. The battery is drawn by src/hud.c.

    python3 tools/genhudglyphs.py           src/hudglyphs.h and Diatom's copy
    python3 tools/genhudglyphs.py --check   whether both are what this draws
                                            (make check-genhudglyphs, out of
                                            the suite: another Pillow or
                                            FreeType draws other pixels; drawn
                                            with Pillow 11.3, FreeType 2.13.3)
"""
import os
import sys

from PIL import Image, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "res", "fonts", "menu.ttf")
OUT = os.path.join(ROOT, "src", "hudglyphs.h")
COPY = os.path.join(ROOT, "diatom", "port", "hudglyphs.h")

CHARS = "0123456789. fpsx\u00b7\u00b0C%:GHzMPUA"
SCALES = (1.0, 0.625)


def type_size(name):
    for line in open(os.path.join(ROOT, "src", "design.h")):
        if line.startswith("#define %s " % name):
            return int(line.split()[2])
    raise SystemExit("no %s in src/design.h" % name)


def table(scale, size_units):
    px = round(size_units * scale)
    font = ImageFont.truetype(FONT, px)
    ascent, descent = font.getmetrics()
    glyphs, alpha = [], []
    for ch in CHARS:
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(alpha)
        if w and h:
            img = Image.new("L", (w, h), 0)
            from PIL import ImageDraw
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
            alpha.extend(img.tobytes())
        adv = round(font.getlength(ch) * 64)
        glyphs.append((ord(ch), adv, x0, y0, w, h, off))
    return px, ascent, descent, glyphs, alpha


def header():
    sizes = (type_size("DS_TYPE_SUPPORT"), type_size("DS_TYPE_CHROME"))
    L = ["/* SPDX-License-Identifier: GPL-3.0-only OR MPL-2.0 */",
         "/* GENERATED by tools/genhudglyphs.py: run it, never edit this.",
         " * On-Screen Stats' characters (src/hud.h) in its two sizes, Lexend Regular",
         " * (res/fonts/menu.ttf, SIL Open Font License 1.1), as alpha bitmaps at the",
         " * two scales the line is drawn at. Either license,",
         " * as src/osdbar.c: Diatom carries a copy in its port/. */",
         "#ifndef ZYPEROS_HUDGLYPHS_H",
         "#define ZYPEROS_HUDGLYPHS_H",
         "",
         "#include <stdint.h>",
         "",
         "/* One character: its code point, its advance in 64ths of a pixel, where",
         " * its bitmap goes from the pen (x right, y down from the line's top) and",
         " * its size, and where its bytes start in the size's alpha */",
         "typedef struct {",
         "\tuint32_t cp;",
         "\tint16_t adv64;",
         "\tint8_t x, y;",
         "\tuint8_t w, h;",
         "\tuint16_t off;",
         "} hudglyph;",
         "",
         "typedef struct {",
         "\tint type;         /* the type's size in units (DS_TYPE_*) */",
         "\tfloat scale;      /* output pixels per unit */",
         "\tint px;           /* the type's size in pixels */",
         "\tint ascent, descent;",
         "\tint n;",
         "\tconst hudglyph *glyph;",
         "\tconst uint8_t *alpha;",
         "} hudglyph_size;",
         "",
         ""]
    names = []
    combos = [(sz, sc) for sz in sizes for sc in SCALES]
    for i, (size, scale) in enumerate(combos):
        px, asc, desc, glyphs, alpha = table(scale, size)
        L.append("static const hudglyph HUDGLYPH_%d[] = {" % i)
        for cp, adv, x, y, w, h, off in glyphs:
            L.append("\t{ 0x%04x, %d, %d, %d, %d, %d, %d }," % (cp, adv, x, y, w, h, off))
        L.append("};")
        L.append("static const uint8_t HUDGLYPH_ALPHA_%d[%d] = {" % (i, max(1, len(alpha))))
        for k in range(0, len(alpha), 16):
            L.append("\t" + ", ".join("%d" % b for b in alpha[k:k + 16]) + ",")
        if not alpha:
            L.append("\t0,")
        L.append("};")
        L.append("")
        names.append((size, scale, px, asc, desc, len(glyphs), i))
    L.append("static const hudglyph_size HUDGLYPH_SIZES[%d] = {" % len(names))
    for size, scale, px, asc, desc, n, i in names:
        L.append("\t{ %d, %.3ff, %d, %d, %d, %d, HUDGLYPH_%d, HUDGLYPH_ALPHA_%d }," % (size, scale, px, asc, desc, n, i, i))
    L.append("};")
    L.append("#define HUDGLYPH_NSIZES %d" % len(names))
    L.append("")
    L.append("#endif")
    return "\n".join(L) + "\n"


def main():
    text = header()
    if "--check" in sys.argv[1:]:
        bad = [p for p in (OUT, COPY) if not os.path.exists(p) or open(p).read() != text]
        for p in bad:
            print("FAIL %s is not what tools/genhudglyphs.py draws: run it" % os.path.relpath(p, ROOT))
        sys.exit(1 if bad else 0)
    for p in (OUT, COPY):
        open(p, "w").write(text)
    print("wrote src/hudglyphs.h and diatom/port/hudglyphs.h")


main()
